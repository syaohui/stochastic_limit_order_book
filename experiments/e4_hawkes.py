"""E4. Bivariate Hawkes model of buy and sell market orders: simulation, MLE, diagnostics.

Output: figures/fig4_hawkes.png, results/e4_hawkes.{json,tex}, results/e4_table.tex
"""
import numpy as np
from scipy import stats

from common import FIG, RES, fmt, write_numbers
from stochastic_lob import hawkes
from stochastic_lob.plotting import WIDE, panel_label, plt, save, use_style

T = 10_000.0       # observation window (s)
TRUE = hawkes.ExpHawkes(
    mu=[0.2, 0.2],
    alpha=[[0.9, 0.2], [0.3, 0.7]],
    beta=[[2.5, 1.5], [1.5, 2.0]],
)


def intensity_on_grid(model, times, types, grid):
    lam = np.tile(model.mu[:, None], (1, len(grid)))
    for t_k, j in zip(times, types):
        later = grid > t_k
        dt = grid[later] - t_k
        lam[:, later] += model.alpha[:, j][:, None] * np.exp(-model.beta[:, j][:, None] * dt)
    return lam


def main():
    use_style()
    times, types = TRUE.simulate(T, rng=41)
    fit, se, res = hawkes.fit_exp_hawkes(times, types, T, 2)
    resid = fit.time_rescaled_residuals(times, types)

    fig, (a1, a2) = plt.subplots(1, 2, figsize=WIDE)
    w = (times > 200) & (times < 260)
    grid = np.linspace(200, 260, 3000)
    lam = intensity_on_grid(TRUE, times[times < 260], types[times < 260], grid)
    a1.plot(grid, lam[0], "-", label=r"Buy Intensity $\Lambda_{1}(t)$")
    a1.plot(grid, lam[1], "-", label=r"Sell Intensity $\Lambda_{2}(t)$")
    top = 1.5 * lam.max()
    a1.plot(times[w & (types == 0)], np.full((w & (types == 0)).sum(), 0.93 * top), "|", ms=7,
            color="C0")
    a1.plot(times[w & (types == 1)], np.full((w & (types == 1)).sum(), 0.85 * top), "|", ms=7,
            color="C1")
    a1.set_xlabel(r"Time $t$ (s)")
    a1.set_ylabel(r"Intensity (s$^{-1}$)")
    a1.set_xlim(200, 260)
    a1.set_ylim(0, 1.25 * top)
    a1.legend(loc="upper left", ncol=2)
    panel_label(a1, "(a)")

    ks = []
    for i, (mk, lab) in enumerate((("o", "Buy"), ("s", "Sell"))):
        r = np.sort(resid[i])
        p = (np.arange(1, len(r) + 1) - 0.5) / len(r)
        sel = np.unique(np.concatenate([np.linspace(0, len(r) - 1, 60).astype(int),
                                        np.arange(max(0, len(r) - 8), len(r))]))
        a2.plot(-np.log1p(-p[sel]), r[sel], mk, ms=3, mfc="white", label=lab)
        ks.append(stats.kstest(resid[i], "expon").pvalue)
    lim = 1.1 * max(r.max() for r in resid)
    a2.plot([0, lim], [0, lim], "-", color="0.3", lw=0.9, label="Unit Exponential")
    a2.set_xlabel("Theoretical Exponential Quantile")
    a2.set_ylabel("Rescaled Waiting Time")
    a2.set_xlim(0, lim)
    a2.set_ylim(0, lim)
    a2.legend(loc="upper left")
    panel_label(a2, "(b)")
    fig.tight_layout()
    save(fig, "fig4_hawkes", FIG)

    # Parameter table: truth, estimate, standard error, z-score.
    rows = []
    names = []
    for i in range(2):
        names.append((rf"$\Lambda^0_{{{i+1}}}$ (s$^{{-1}}$)", TRUE.mu[i], fit.mu[i], se.mu[i]))
    for p_name, tr, es, er in (("alpha", TRUE.alpha, fit.alpha, se.alpha),
                               ("beta", TRUE.beta, fit.beta, se.beta)):
        for i in range(2):
            for j in range(2):
                sym = r"\alpha" if p_name == "alpha" else r"\beta"
                names.append((rf"${sym}_{{{i+1}{j+1}}}$ (s$^{{-1}}$)", tr[i, j], es[i, j], er[i, j]))
    zs = []
    for lab, tr, es, er in names:
        z = (es - tr) / er
        zs.append(z)
        rows.append(f"{lab} & {tr:.2f} & {es:.3f} & {er:.3f} & {z:+.2f} \\\\")
    table = "\n".join([
        "% generated by experiments/e4_hawkes.py; do not edit",
        r"\begin{tabular}{lrrrr}",
        r"\hline",
        r"Parameter & True & Estimate & Std.\ error & $z$ \\",
        r"\hline",
        *rows,
        r"\hline",
        r"\end{tabular}",
    ])
    (RES / "e4_table.tex").write_text(table + "\n")

    write_numbers("e4_hawkes", {
        "EfourT": f"{int(T):,}".replace(",", "{,}"),
        "EfourNbuy": f"{int((types == 0).sum()):,}".replace(",", "{,}"),
        "EfourNsell": f"{int((types == 1).sum()):,}".replace(",", "{,}"),
        "EfourRho": fmt(TRUE.spectral_radius, 3),
        "EfourRhoFit": fmt(fit.spectral_radius, 3),
        "EfourMaxZ": fmt(np.max(np.abs(zs)), 2),
        "EfourKSbuy": fmt(ks[0], 2),
        "EfourKSsell": fmt(ks[1], 2),
        "EfourLamBuy": fmt(TRUE.stationary_intensity()[0], 3),
        "EfourLamSell": fmt(TRUE.stationary_intensity()[1], 3),
    })


if __name__ == "__main__":
    main()
