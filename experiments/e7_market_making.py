"""E7. Market making: Avellaneda-Stoikov quotes against a symmetric benchmark, and GLFT quotes.

Output: figures/fig8_market_making.png, results/e7_market_making.{json,tex}, results/e7_table.tex
"""
import numpy as np

from common import FIG, RES, fmt, write_numbers
from stochastic_lob import market_making as mm
from stochastic_lob.plotting import WIDE, panel_label, plt, save, use_style

N_PATHS = 1000
GAMMAS = (0.01, 0.1, 0.5)


def main():
    use_style()
    base = mm.MMParams()
    fig, (a1, a2) = plt.subplots(1, 2, figsize=WIDE)

    q = np.arange(-6, 7)
    db, da = mm.as_quotes(base.S0, q, 0.0, base)
    gb, ga = mm.glft_quotes(q, base)
    a1.plot(q, db, "o-", ms=3, label=r"AS Bid $d^{b}$")
    a1.plot(q, da, "s-", ms=3, label=r"AS Ask $d^{a}$")
    a1.plot(q, gb, "o--", ms=3, mfc="white", label=r"GLFT Bid $d^{b}$")
    a1.plot(q, ga, "s--", ms=3, mfc="white", label=r"GLFT Ask $d^{a}$")
    a1.axhline(0, color="0.5", lw=0.6)
    a1.set_xlabel(r"Inventory $y$ (shares)")
    a1.set_ylabel(r"Quote Distance From Mid (currency)")
    a1.set_ylim(-2, 5.5)
    a1.legend(loc="upper center", ncol=2)
    panel_label(a1, "(a)")

    rows = []
    num = {"EsevenNpaths": f"{N_PATHS:,}".replace(",", "{,}")}
    hist = None
    for g in GAMMAS:
        p = mm.MMParams(gamma=g)
        r_inv = mm.simulate(mm.as_quotes, p, N_PATHS, rng=71)
        r_sym = mm.simulate(mm.symmetric_quotes, p, N_PATHS, rng=72)
        for name, r in (("Inventory (AS)", r_inv), ("Symmetric", r_sym)):
            pr = r["profit"]
            rows.append(f"{g:g} & {name} & {pr.mean():.2f} $\\pm$ {pr.std(ddof=1)/np.sqrt(N_PATHS):.2f} "
                        f"& {pr.std(ddof=1):.2f} & {r['q_T'].mean():+.2f} & {r['q_T'].std(ddof=1):.2f} \\\\")
        if g == 0.1:
            hist = (r_inv["profit"], r_sym["profit"])
            num["EsevenInvMean"] = fmt(r_inv["profit"].mean(), 1)
            num["EsevenSymMean"] = fmt(r_sym["profit"].mean(), 1)
            num["EsevenInvStd"] = fmt(r_inv["profit"].std(ddof=1), 1)
            num["EsevenSymStd"] = fmt(r_sym["profit"].std(ddof=1), 1)
        rows.append(r"\hline")

    bins = np.linspace(min(h.min() for h in hist), max(h.max() for h in hist), 40)
    a2.hist(hist[0], bins=bins, histtype="stepfilled", alpha=0.55, label="Inventory Strategy")
    a2.hist(hist[1], bins=bins, histtype="step", lw=1.3, label="Symmetric Strategy")
    a2.set_xlabel(r"Terminal Profit $\Pi_T$ (currency)")
    a2.set_ylabel("Number of Paths")
    a2.set_ylim(0, 1.45 * a2.get_ylim()[1])
    a2.legend(loc="upper left")
    panel_label(a2, "(b)")
    fig.tight_layout()
    save(fig, "fig8_market_making", FIG)

    table = "\n".join([
        "% generated by experiments/e7_market_making.py; do not edit",
        r"\begin{tabular}{llrrrr}",
        r"\hline",
        r"$\gamma$ & Strategy & Mean $\Pi_T$ & Std $\Pi_T$ & Mean $y_T$ & Std $y_T$ \\",
        r"\hline",
        *rows,
        r"\end{tabular}",
    ])
    (RES / "e7_table.tex").write_text(table + "\n")
    omega = np.sqrt(base.sigma ** 2 * base.gamma / (2 * base.k * base.A)
                    * (1 + base.gamma / base.k) ** (1 + base.k / base.gamma))
    num["EsevenOmega"] = fmt(omega, 3)
    num["EsevenHalfSpreadT"] = fmt(np.log1p(base.gamma / base.k) / base.gamma, 3)
    num["EsevenSpreadZero"] = fmt(base.gamma * base.sigma ** 2 * base.T
                                  + 2 / base.gamma * np.log1p(base.gamma / base.k), 3)
    write_numbers("e7_market_making", num)


if __name__ == "__main__":
    main()
