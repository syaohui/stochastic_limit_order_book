"""E11. Exact optimal market making with inventory limits, against approximations.

Uses the GLFT (2013) example parameters, in ticks and seconds: sigma = 0.3
tick/sqrt(s), A = 0.9 1/s, k = 0.3 1/tick, gamma = 0.01 1/tick, T = 600 s, Q = 30.

Output: figures/fig11_glft_exact.png, results/e11_glft_exact.{json,tex}, results/e11_table.tex
"""
import numpy as np

from common import FIG, RES, fmt, write_numbers
from stochastic_lob import market_making as mm
from stochastic_lob.plotting import WIDE, panel_label, plt, save, use_style

P = mm.MMParams(S0=0.0, T=600.0, sigma=0.3, dt=0.2, gamma=0.01, k=0.3, A=0.9)
Q = 30
N_PATHS = 2000


def main():
    use_style()
    fig, (a1, a2, a3) = plt.subplots(1, 3, figsize=(7.2, 2.6))
    q = np.arange(-Q, Q + 1)

    sb, sa = mm.glft_stationary_quotes(Q, P)
    gb, ga = mm.glft_quotes(q, P)
    asb, asa = mm.as_quotes(0.0, q, 0.0, P)
    a1.plot(q[:-1], sb[:-1], "-", label="Exact, Bid")
    a1.plot(q[:-1], gb[:-1], "--", label="Closed Form, Bid")
    a1.plot(q[:-1], asb[:-1], ":", color="0.3", label="AS, Bid, $t=0$")
    a1.set_xlabel(r"Inventory $y$ (shares)")
    a1.set_ylabel(r"Bid Distance $d^b$ (ticks)")
    a1.set_ylim(-4, 14)
    a1.legend(loc="upper left", fontsize=7)
    panel_label(a1, "(a)")

    taus = np.linspace(0, 600, 301)
    db, _ = mm.glft_exact_quotes(Q, P, taus)
    for y, mk in ((-10, "-"), (0, "--"), (10, ":")):
        a2.plot(taus, db[:, y + Q], mk, label=rf"$y = {y}$")
    a2.set_xlabel(r"Time to Horizon $T - t$ (s)")
    a2.set_ylabel(r"Bid Distance $d^b$ (ticks)")
    a2.set_ylim(2, 6.5)
    a2.legend(loc="upper right", ncol=3, fontsize=7)
    panel_label(a2, "(b)")

    drifts = np.linspace(-0.01, 0.01, 21)
    b0 = [mm.glft_exact_quotes(Q, P, [600.0], m)[0][0, Q] for m in drifts]
    a0 = [mm.glft_exact_quotes(Q, P, [600.0], m)[1][0, Q] for m in drifts]
    a3.plot(drifts * 1e3, b0, "-", label=r"Bid $d^b$")
    a3.plot(drifts * 1e3, a0, "--", label=r"Ask $d^a$")
    a3.set_xlabel(r"Drift $m$ ($10^{-3}$ ticks s$^{-1}$)")
    a3.set_ylabel(r"Quote Distance at $y = 0$ (ticks)")
    a3.set_ylim(2.6, 4.4)
    a3.legend(loc="upper center", ncol=2, fontsize=7)
    panel_label(a3, "(c)")
    fig.tight_layout()
    save(fig, "fig11_glft_exact", FIG)

    # Strategy comparison: exact GLFT against the AS approximation and a symmetric benchmark.
    rows = []
    results = {}
    for name, strat in (("Exact GLFT", mm.glft_strategy(Q, P)), ("AS approximation", mm.as_quotes),
                        ("Symmetric", mm.symmetric_quotes)):
        r = mm.simulate(strat, P, N_PATHS, rng=111)
        results[name] = r
        pr = r["profit"]
        rows.append(f"{name} & {pr.mean():.1f} $\\pm$ {pr.std(ddof=1)/np.sqrt(N_PATHS):.1f} & "
                    f"{pr.std(ddof=1):.1f} & {mm.certainty_equivalent(pr, P.gamma):.1f} \\\\")
    table = "\n".join(["% generated by experiments/e11_glft_exact.py; do not edit",
                       r"\begin{tabular}{lrrr}", r"\hline",
                       r"Strategy & Mean $\Pi_T$ & Std $\Pi_T$ & CE \\", r"\hline",
                       *rows, r"\hline", r"\end{tabular}"])
    (RES / "e11_table.tex").write_text(table + "\n")

    ce = {k: mm.certainty_equivalent(v["profit"], P.gamma) for k, v in results.items()}
    write_numbers("e11_glft_exact", {
        "EelevenMaxApproxErr": fmt(np.max(np.abs(sb[Q - 5:Q + 6] - gb[Q - 5:Q + 6])), 3),
        "EelevenHalfSpreadZero": fmt(sb[Q], 2),
        "EelevenCEexact": fmt(ce["Exact GLFT"], 1),
        "EelevenCEas": fmt(ce["AS approximation"], 1),
        "EelevenCEsym": fmt(ce["Symmetric"], 1),
        "EelevenNpaths": f"{N_PATHS:,}".replace(",", "{,}"),
    })


if __name__ == "__main__":
    main()
