"""Paths and helpers shared by the experiment scripts."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

FIG = ROOT / "figures"
RES = ROOT / "results"
RES.mkdir(exist_ok=True)


def write_numbers(name: str, numbers: dict):
    """Store results as JSON and as LaTeX macros that the paper \\input's.

    Every number quoted in the paper comes from one of these files, so the
    text and the code cannot drift apart. Macro names must be letters only.
    """
    (RES / f"{name}.json").write_text(json.dumps(numbers, indent=2))
    lines = [f"% generated by experiments/{name}.py; do not edit"]
    for key, val in numbers.items():
        if not key.isalpha():
            raise ValueError(f"macro name must be letters only: {key}")
        lines.append(f"\\newcommand{{\\{key}}}{{{val}}}")
    (RES / f"{name}.tex").write_text("\n".join(lines) + "\n")


def fmt(x, nd=3):
    return f"{x:.{nd}f}"


def fmt_pm(x, se, nd=3):
    return f"{x:.{nd}f} \\pm {se:.{nd}f}"
